#!/usr/bin/env node
// Bundles the camera bridge (larszu/lz-camera-bridge, packages/bridge) into one CommonJS file,
// electron/camera-bridge.cjs, which electron/main.cjs starts in the main process. Same pattern as
// lz-camera-bridge's own desktop app (packages/electron-app/scripts/build-bridge.mjs): one bundle
// without open ends, so nothing has to be resolved from node_modules inside the asar archive.
//
// Source, first found: $LZS_CAMERA_BRIDGE_DIR, vendor/lz-camera-bridge (the CI checks the pinned
// tag out there, scripts/camera-bridge.json), ../lz-camera-bridge (a clone next to this repo).
// Bare imports of the bridge (ws, ssh2) resolve from this repo's node_modules, so the bridge
// repo needs no `npm install`.
//
// Kept outside the bundle: serialport (native, N-API prebuilds → no electron-rebuild, unpacked
// from the asar archive by electron-builder.js) and usb / node-hid, which are not shipped: the
// bridge loads them lazily and reports their absence (Sony over USB and USB control surfaces
// need the LZ Camera Bridge app).
//
// Without a source: --required (release builds, CI) fails, otherwise a warning – the app then
// starts without the built-in bridge and says so.

import * as esbuild from 'esbuild';
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const pin = JSON.parse(readFileSync(join(root, 'scripts', 'camera-bridge.json'), 'utf8'));
const required = process.argv.includes('--required') || process.env.CI === 'true';
const out = join(root, 'electron', 'camera-bridge.cjs');

const candidates = [process.env.LZS_CAMERA_BRIDGE_DIR, join(root, 'vendor', 'lz-camera-bridge'), join(root, '..', 'lz-camera-bridge')].filter(Boolean);
const dir = candidates.find((d) => existsSync(join(d, pin.entry)));
if (!dir) {
  const msg = `camera bridge source not found (${pin.repo} ${pin.ref}); looked in:\n  ${candidates.join('\n  ')}`;
  if (required) { console.error(`error: ${msg}`); process.exit(1); }
  console.warn(`warning: ${msg}\n  the desktop app starts without the built-in camera bridge`);
  process.exit(0);
}

// which version is bundled (shown in the app and the feedback report); a clone off the pinned tag warns
let version = 'unknown';
try {
  // only the bridge's own repository counts (a copy inside vendor/ would report this repo's tag)
  const top = execFileSync('git', ['-C', dir, 'rev-parse', '--show-toplevel'], { encoding: 'utf8' }).trim();
  if (resolve(top) !== resolve(dir)) throw new Error('not a repository root');
  version = execFileSync('git', ['-C', dir, 'describe', '--tags', '--always'], { encoding: 'utf8' }).trim();
  if (version !== pin.ref) {
    const msg = `camera bridge source at ${version}, pinned ${pin.ref} (${dir})`;
    // a release ships exactly the pinned bridge; a local clone ahead of the tag is fine for development
    if (required && process.env.CI === 'true') { console.error(`error: ${msg}`); process.exit(1); }
    console.warn(`warning: ${msg}`);
  }
} catch { version = `${pin.ref} (copy without git)`; }

await esbuild.build({
  entryPoints: [join(dir, pin.entry)],
  outfile: out,
  bundle: true,
  platform: 'node',
  // Electron 44 runs Node 24; node22 stays readable for every main process we ship
  target: 'node22',
  format: 'cjs',
  external: ['serialport', 'usb', 'node-hid'],
  nodePaths: [join(root, 'node_modules')],
  // ssh2's optional native accelerators (cpu-features, sshcrypto.node) are tried with require
  // inside try/catch; left out, ssh2 uses its JavaScript paths
  logLevel: 'warning',
  banner: { js: `// lz-camera-bridge ${version} – generated by scripts/build-camera-bridge.mjs, do not edit` },
});
mkdirSync(dirname(out), { recursive: true });
writeFileSync(join(root, 'electron', 'camera-bridge.json'), JSON.stringify({ repo: pin.repo, ref: pin.ref, version }, null, 2) + '\n');
console.log(`camera bridge ${version} → electron/camera-bridge.cjs`);
